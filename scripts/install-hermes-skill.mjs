#!/usr/bin/env node
/**
 * Pack and install the trading-wiki skill into a target agent (Hermes by default).
 *
 * Usage:
 *   npm run skill:install:hermes
 *   node scripts/install-hermes-skill.mjs --agent hermes
 *   node scripts/install-hermes-skill.mjs --agent hermes --target ~/.hermes/skills/trading-wiki
 */
import { chmod, cp, mkdir, readFile, writeFile } from "node:fs/promises"
import os from "node:os"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(__dirname, "..")
const SOURCE_SKILL = path.join(REPO_ROOT, ".hermes-skills", "trading-wiki")

const AGENTS = {
  hermes: {
    label: "Hermes Agent",
    defaultTarget: path.join(os.homedir(), ".hermes", "skills", "trading-wiki"),
    verifyCmd: "/skills search trading-wiki",
  },
}

function parseArgs(argv) {
  const args = { agent: "hermes", target: null, dryRun: false, help: false }
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i]
    if (token === "--help" || token === "-h") {
      args.help = true
      continue
    }
    if (token === "--dry-run") {
      args.dryRun = true
      continue
    }
    if (token === "--agent") {
      args.agent = argv[++i]
      continue
    }
    if (token === "--target") {
      args.target = argv[++i]?.replace(/^~(?=\/|$)/, os.homedir())
      continue
    }
    throw new Error(`Unknown argument: ${token}`)
  }
  return args
}

function printHelp() {
  console.log(`Pack and install trading-wiki skill for an agent runtime.

Usage:
  npm run skill:install:hermes
  node scripts/install-hermes-skill.mjs [--agent hermes] [--target <dir>] [--dry-run]

Options:
  --agent hermes     Target agent runtime (default: hermes)
  --target <dir>      Override install directory
  --dry-run           Show actions without writing files
  --help              Show this help

Environment:
  HERMES_SKILLS_TARGET   Override Hermes install path

Supported agents:
${Object.keys(AGENTS)
  .map((key) => `  - ${key}: ${AGENTS[key].label} -> ${AGENTS[key].defaultTarget}`)
  .join("\n")}
`)
}

async function assertSourceSkill() {
  const required = [
    path.join(SOURCE_SKILL, "SKILL.md"),
    path.join(SOURCE_SKILL, "scripts", "tw-cli.sh"),
  ]
  for (const file of required) {
    await readFile(file, "utf8")
  }
}

async function writeInstallMeta(targetDir, meta) {
  const envSh = `# Generated by npm run skill:install:hermes — do not edit.
export TRADING_WIKI_REPO="${meta.repoRoot.replace(/"/g, '\\"')}"
`
  await writeFile(path.join(targetDir, "scripts", "env.sh"), envSh, "utf8")
  await writeFile(
    path.join(targetDir, "INSTALL.json"),
    `${JSON.stringify(meta, null, 2)}\n`,
    "utf8",
  )
}

async function installSkill({ agentKey, targetDir, dryRun }) {
  const agent = AGENTS[agentKey]
  if (!agent) {
    throw new Error(`Unsupported agent: ${agentKey}. Supported: ${Object.keys(AGENTS).join(", ")}`)
  }

  await assertSourceSkill()

  const meta = {
    agent: agentKey,
    skill: "trading-wiki",
    version: JSON.parse(await readFile(path.join(REPO_ROOT, "package.json"), "utf8")).version,
    repoRoot: REPO_ROOT,
    installedAt: new Date().toISOString(),
    targetDir,
  }

  console.log(`[pack]   validate source skill at ${SOURCE_SKILL}`)
  console.log(`[pack]   repo root: ${REPO_ROOT}`)
  console.log(`[install] agent: ${agent.label}`)
  console.log(`[install] target: ${targetDir}`)

  if (dryRun) {
    console.log("[dry-run] would copy skill files and write scripts/env.sh")
    return meta
  }

  await mkdir(path.dirname(targetDir), { recursive: true })
  await cp(SOURCE_SKILL, targetDir, { recursive: true, force: true })
  await writeInstallMeta(targetDir, meta)
  await chmod(path.join(targetDir, "scripts", "tw-cli.sh"), 0o755)
  await chmod(path.join(targetDir, "scripts", "env.sh"), 0o644)

  console.log(`[done]   installed to ${targetDir}`)
  console.log("")
  console.log("Next steps:")
  console.log(`  1. Restart ${agent.label}`)
  console.log(`  2. In Hermes: ${agent.verifyCmd}`)
  console.log(`  3. Test: bash ${targetDir}/scripts/tw-cli.sh help`)
  console.log("")
  console.log("Ensure these env vars are visible to Hermes terminal sessions:")
  console.log("  TRADING_WIKI_PROJECT, DEEPSEEK_API_KEY (or OPENAI_API_KEY), OPENAI_API_BASE, OPENAI_MODEL")
  console.log("  Optional: TRADING_WIKI_REASONING_EFFORT=low, TRADING_WIKI_PAGE_CONCURRENCY=3")
  console.log("  Optional (PG): PG_SHIHAO_* or PG_SHIHAO_CONFIG_PATH")

  return meta
}

async function main() {
  const args = parseArgs(process.argv.slice(2))
  if (args.help) {
    printHelp()
    return
  }

  const agent = AGENTS[args.agent]
  if (!agent) {
    throw new Error(`Unsupported agent: ${args.agent}`)
  }

  const targetDir = path.resolve(
    args.target ?? process.env.HERMES_SKILLS_TARGET ?? agent.defaultTarget,
  )

  await installSkill({
    agentKey: args.agent,
    targetDir,
    dryRun: args.dryRun,
  })
}

main().catch((err) => {
  console.error(err.message ?? err)
  process.exit(1)
})
